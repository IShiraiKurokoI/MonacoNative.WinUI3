#!/usr/bin/env python3
"""Execute native language behavior tests, without a .NET/Node runtime.

The checked-in scanner fixture was generated by the pinned TypeScript 5.8.3
scanner. --typescript-js optionally reruns that upstream development oracle;
Node is never part of the editor's runtime. C++ integration requires an explicit
libclang path and is reported SKIPPED (not passed) when no library is supplied.
"""
import argparse
import ctypes as C
import json
import os
from pathlib import Path
import random
import subprocess
from concurrent.futures import ThreadPoolExecutor

ROOT = Path(__file__).resolve().parents[1]

class Document(C.Structure):
    _fields_ = [("path", C.c_char_p), ("text", C.c_char_p), ("length", C.c_size_t)]

class Native:
    def __init__(self, library, clang=None):
        self.lib = C.CDLL(str(Path(library).resolve()))
        self.lib.mn_language_abi_version.restype = C.c_uint32
        assert self.lib.mn_language_abi_version() == 1
        self.lib.mn_language_free.argtypes = [C.c_void_p]
        self.lib.mn_cpp_create.argtypes = [C.c_char_p, C.POINTER(C.c_void_p)]
        self.lib.mn_cpp_create.restype = C.c_void_p
        self.lib.mn_cpp_destroy.argtypes = [C.c_void_p]
        self.lib.mn_cpp_request.argtypes = [C.c_void_p, C.POINTER(Document), C.c_uint32,
                                           C.POINTER(C.c_char_p), C.c_uint32, C.c_uint32,
                                           C.c_size_t, C.POINTER(C.c_void_p)]
        self.lib.mn_typescript_request.argtypes = [C.POINTER(Document), C.c_uint32,
                                                  C.c_uint32, C.c_size_t, C.POINTER(C.c_void_p)]
        self.handle = None
        if clang:
            error = C.c_void_p()
            self.handle = self.lib.mn_cpp_create(os.fsencode(str(Path(clang).resolve())), C.byref(error))
            reason = self.take(error)
            assert self.handle, reason

    def take(self, pointer):
        if not pointer: return {}
        try: return json.loads(C.string_at(pointer).decode("utf-8"))
        finally: self.lib.mn_language_free(pointer)

    def request(self, text, operation=0, cpp=False, marked=True, additional=(), arguments=()):
        if marked:
            at = text.index("|"); text = text[:at] + text[at + 1:]
        else: at = 0
        data = text.encode("utf-8")
        # No source files are written. libclang consumes the unsaved snapshots.
        path = str((ROOT / "artifacts" / ("native-test.cpp" if cpp else "native-test.ts")).resolve()).encode()
        buffers = [(path, data)] + [(os.fsencode(p), t.encode()) for p, t in additional]
        docs = (Document * len(buffers))(*(Document(p, t, len(t)) for p, t in buffers))
        result = C.c_void_p(); offset = len(text[:at].encode())
        if cpp:
            assert self.handle, "C++ test requested without a libclang session"
            args = [b"-xc++", b"-std=c++20", b"-Wno-everything"] + [os.fsencode(v) for v in arguments]
            pointers = (C.c_char_p * len(args))(*args)
            ok = self.lib.mn_cpp_request(self.handle, docs, len(docs), pointers, len(args), operation, offset, C.byref(result))
        else:
            ok = self.lib.mn_typescript_request(docs, len(docs), operation, offset, C.byref(result))
        value = self.take(result)
        assert ok == 1, value
        return value

    def close(self):
        if self.handle: self.lib.mn_cpp_destroy(self.handle); self.handle = None

def canonical(tokens):
    return [[t["kind"], t["start"], t["end"],
             t.get("value") if t["kind"] in (9,10,11,14,15,16,17,18) or t["kind"] >= 80 else None,
             t["flags"]] for t in tokens]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-library", default=os.getenv("MONACONATIVE_NATIVE_LIBRARY"), required=not os.getenv("MONACONATIVE_NATIVE_LIBRARY"))
    parser.add_argument("--libclang", default=os.getenv("MONACONATIVE_LIBCLANG"))
    parser.add_argument("--clang-resource-dir", help="Optional Clang resource directory; also exercises STL template completion")
    parser.add_argument("--typescript-js", help="Optional installed TypeScript 5.8.3 lib/typescript.js, for the development oracle")
    args = parser.parse_args()
    native = Native(args.native_library, args.libclang)
    try:
        fixtures = json.loads((ROOT / "tests/LanguageTests/Fixtures/TypeScriptScanner.json").read_text(encoding="utf-8"))
        cases = fixtures["cases"]
        if args.typescript_js:
            oracle = r'''const ts=require(process.argv[1]);if(ts.version!=='5.8.3')throw Error('Expected TypeScript 5.8.3');let input='';process.stdin.on('data',d=>input+=d);process.stdin.on('end',()=>console.log(JSON.stringify(JSON.parse(input).map(text=>{const s=ts.createScanner(ts.ScriptTarget.Latest,false,ts.LanguageVariant.Standard,text),out=[];while(true){let k=s.scan();out.push([k,s.getTokenPos(),s.getTextPos(),[9,10,11,14,15,16,17,18].includes(k)||k>=80?s.getTokenValue():null,s.getTokenFlags()]);if(k===1)break;}return out;}))));'''
            expected = json.loads(subprocess.run(["node", "-e", oracle, str(Path(args.typescript_js).resolve())], input=json.dumps([c["text"] for c in cases]), capture_output=True, text=True, check=True).stdout)
            assert expected == [c["tokens"] for c in cases], "Pinned upstream fixtures drifted"
        for i, case in enumerate(cases):
            actual = canonical(native.request(case["text"], 5, marked=False)["tokens"])
            assert actual == case["tokens"], (i, case["text"], actual, case["tokens"])
        print(f"PASS: {len(cases)} TypeScript 5.8.3 scanner differential fixtures")

        contexts = [
            ('class User { name: string; greet(who: string, count: number): void {} private secret: number; static create(): User {} } const user = new User(); user.|', {'name','greet'}, {'secret','create'}),
            ('interface Settings { enabled: boolean; theme: string; } const config: Settings = { enabled: true, theme: "dark" }; config.|', {'enabled','theme'}, set()),
            ('const model = { count: 1, label: "hello", nested: { x: 1 }, run(amount: number) {} }; model.|', {'count','label','nested','run'}, set()),
            ('const model = { nested: { x: 1 } }; model.nested.|', {'x'}, set()),
            ('class A { field: number; } function test(arg: A) { arg.| }', {'field'}, set()),
            ('class A { a: number; } class B extends A { b: number; } let obj: B; obj.|', {'a','b'}, set()),
            ('class A { field: number; } function get(): A { return new A(); } get().|', {'field'}, set()),
            ('class A { field: number; } const obj: A = new A(); obj?.|', {'field'}, set()),
            ('class A { a: number; } class B { b: number; } let item: A; { let item: B; item.| }', {'b'}, {'a'}),
            ('class A { a: number; } class B { b: number; } let item: A; { let item: B; } item.|', {'a'}, {'b'}),
            ('type Options = { width: number; height: number; }; let opts: Options; opts.|', {'width','height'}, set()),
            ('// obj.|', set(), {'const'}),
            ('const s = "abc|def";', set(), {'const'}),
            ('const s = "abc|', set(), {'const'}),
            ('// 中文😀\r\nclass A { 中文: string; } const obj = new A(); obj.|', {'中文'}, set()),
            ('console.|', {'log','warn','error'}, set()),
            ('const title = "hello"; title.|', {'length','substring','toUpperCase'}, set()),
            ('const xs = [1,2]; xs.|', {'map','filter','length'}, set()),
            ('class Mine { custom(): void {} } const console = new Mine(); console.|', {'custom'}, {'log'}),
            ('class A { static make(): A {} field: number; } A.|', {'make'}, {'field'}),
        ]
        for text, expected, forbidden in contexts:
            result = native.request(text)
            labels = {v["label"] for v in result["items"]}
            assert expected <= labels and not (forbidden & labels), (text, expected, forbidden, labels)
        methods = native.request('class A { run(x: number, y: string): void {} } const a = new A(); a.|')["items"]
        assert next(v for v in methods if v["label"] == "run")["snippet"] == 'run(${1:x}, ${2:y})$0'
        getter = native.request('class A { get length(): number { return 1; } } let a: A; a.|')["items"]
        assert next(v for v in getter if v['label']=='length')['snippet'] == 'length'
        source = '// 中文😀\r\nclass A { field: number; } const a = new A(); a.fi|eld;'
        definition = native.request(source, 3)["locations"][0]
        assert definition["start"] == source.encode().index(b"field")
        hovered = native.request(source, 2)
        assert "A.field: number" in hovered["hover"]
        replacement = next(v for v in native.request(source)["items"] if v["label"] == "field")
        assert replacement["end"] - replacement["start"] == 5
        assert native.request('"unterminated|', 1)["diagnostics"]
        cancelled = C.c_void_p()
        assert native.lib.mn_typescript_request(None, 0, 0, 0, C.byref(cancelled)) == 0
        assert "error" in native.take(cancelled)
        print(f"PASS: {len(contexts) + 7} TypeScript scope/member/snippet/Unicode/ABI scenarios")
        with ThreadPoolExecutor(max_workers=4) as pool:
            values = list(pool.map(lambda _: native.request('console.|'), range(64)))
        assert all(any(v['label']=='log' for v in r['items']) for r in values)
        print("PASS: 64 concurrent native TypeScript requests")

        # Snapshot-only ES modules: no disk crawling, Node or upstream server.
        module_path = str((ROOT / 'artifacts' / 'widget.ts').resolve())
        barrel_path = str((ROOT / 'artifacts' / 'barrel.ts').resolve())
        other_path = str((ROOT / 'artifacts' / 'other.ts').resolve())
        module = ('// 中文😀\nexport class Widget { count: number; run(x: number, y: string): void {} private secret: string; }\n'
                  'export function make(): Widget { return new Widget(); }\nconst internalOnly = 2;\nexport default Widget;')
        imports = [
            ('import { Widget } from "./widget"; let w: Widget; w.|', {'count', 'run'}, {'secret'}),
            ('import { Widget as Other } from "./widget"; const w = new Other(); w.|', {'count', 'run'}, {'secret'}),
            ('import Widget from "./widget"; const w = new Widget(); w.|', {'count', 'run'}, set()),
            ('import Widget, { make } from "./widget"; const w = make(); w.|', {'count', 'run'}, set()),
            ('import * as m from "./widget"; m.|', {'Widget', 'make', 'default'}, {'internalOnly'}),
            ('import * as m from "./widget"; const w = new m.Widget(); w.|', {'count', 'run'}, set()),
            ('import * as m from "./widget"; const w = m.make(); w.|', {'count', 'run'}, set()),
            ('import { make } from "./widget"; make().|', {'count', 'run'}, set()),
            ('import { make } from "./widget"; const w = make(); w.|', {'count', 'run'}, set()),
            ('import { Widget } from "./widget.js"; let w: Widget; w.|', {'count', 'run'}, set()),
            ('import type { Widget } from "./widget"; let w: Widget; w.|', {'count', 'run'}, set()),
            ('import { type Widget as W } from "./widget"; let w: W; w.|', {'count', 'run'}, set()),
            ('import { Widget } from "./widget"; class Child extends Widget { own: string; } let w: Child; w.|', {'count', 'run', 'own'}, {'secret'}),
            ('import { Widget } from "./widget"; |', {'Widget'}, {'make', 'internalOnly'}),
            ('import { internalOnly } from "./widget"; |', set(), {'internalOnly'}),
            ('import { Widget } from "package-not-loaded"; let w: Widget; w.|', set(), {'count', 'run'}),
        ]
        for text, expected, forbidden in imports:
            labels = {v['label'] for v in native.request(text, additional=[(module_path, module)])['items']}
            assert expected <= labels and not forbidden & labels, (text, labels, expected, forbidden)
        code = 'import { Widget } from "./widget"; let w: Widget; w.co|unt;'
        target = native.request(code, 3, additional=[(module_path, module)])['locations'][0]
        assert Path(target['file']) == Path(module_path) and target['start'] == module.encode().index(b'count')
        hover = native.request(code, 2, additional=[(module_path, module)])
        assert 'count: number' in hover['hover']
        selected = next(v for v in native.request(imports[0][0], additional=[(module_path, module)])['items'] if v['label'] == 'run')
        assert selected['snippet'] == 'run(${1:x}, ${2:y})$0'
        for reexport, name in [('export { Widget as Public } from "./widget";', 'Public'), ('export * from "./widget";', 'Widget')]:
            labels = {v['label'] for v in native.request(f'import {{ {name} }} from "./barrel"; let w: {name}; w.|',
                additional=[(module_path, module), (barrel_path, reexport)])['items']}
            assert {'count', 'run'} <= labels
        labels = {v['label'] for v in native.request('import { Widget as A } from "./widget"; import { Widget as B } from "./other"; let b: B; b.|',
            additional=[(module_path, module), (other_path, 'export class Widget { other: number; }')])['items']}
        assert 'other' in labels and 'count' not in labels
        updated = native.request(imports[0][0], additional=[(module_path, 'export class Widget { changed: number; }')])
        assert 'changed' in {v['label'] for v in updated['items']} and 'count' not in {v['label'] for v in updated['items']}
        nested = str((ROOT / 'artifacts' / 'nested' / 'index.ts').resolve())
        labels = {v['label'] for v in native.request('import { Widget } from "./nested"; let w: Widget; w.|', additional=[(nested, module)])['items']}
        assert {'count', 'run'} <= labels
        # Ambiguous star exports must not invent one of the conflicting classes.
        labels = {v['label'] for v in native.request('import * as b from "./barrel"; b.|', additional=[
            (module_path, module), (other_path, 'export class Widget { other: number; }'),
            (barrel_path, 'export * from "./widget"; export * from "./other";')])['items']}
        assert 'Widget' not in labels and 'default' not in labels and 'make' in labels
        # Cycles terminate. Full TypeScript cyclic type inference is not implemented.
        native.request('import * as a from "./widget"; a.|', additional=[
            (module_path, 'import { B } from "./other"; export class A { a: number; }'),
            (other_path, 'import { A } from "./widget"; export class B { b: number; }')])
        print(f"PASS: {len(imports) + 10} TypeScript snapshot module/linking/navigation/isolation scenarios")

        # Exercise the exact shipped Sample sources, not only synthetic module strings.
        sample_root = ROOT / 'src/MonacoNative.SampleApp/Assets/Samples'
        sample_source = (sample_root / 'demo.ts').read_text(encoding='utf-8')
        # The shipped basic sample is deliberately self-contained. The earlier
        # module scenarios above still protect the optional snapshot-import API.
        sample_docs = []
        for expression, expected_members in [('person.|', {'name', 'count'}),
                                              ('greeter.|', {'prefix', 'greet'}),
                                              ('console.|', {'log'})]:
            labels = {v['label'] for v in native.request(sample_source + '\n' + expression, additional=sample_docs)['items']}
            assert expected_members <= labels, (expression, labels)
        print('PASS: 3 shipped single-file TypeScript Sample/native completion scenarios')

        rng = random.Random(5817)
        atoms = ['class', 'interface', 'type', 'function', 'const', 'let', 'new', 'extends',
                 'private', 'static', 'get', 'set', 'this', 'foo', 'bar', 'number',
                 '{', '}', '(', ')', '[', ']', ':', ';', ',', '.', '?', '=', '=>',
                 '"text"', '42', '/*comment*/', '变量', '`value ${x}`']
        for _ in range(512):
            source = ' '.join(rng.choices(atoms, k=rng.randrange(0, 100))) + '|'
            native.request(source)
            native.request(source, 1)
        print("PASS: 512 deterministic malformed-source completion/diagnostic pairs (robustness, not upstream parity)")

        if native.handle:
            source = 'struct Widget { int count; void run(int times, double scale); private: int secret; }; void f() { Widget w; w.| }'
            result = native.request(source, cpp=True); items = result["items"]
            labels = {v["label"] for v in items}; assert {'count','run'} <= labels and 'secret' not in labels
            method = next(v for v in items if v['label']=='run'); assert method['kind']=='Method' and '${1:' in method['snippet'] and '${2:' in method['snippet']
            assert next(v for v in items if v['label']=='count')['kind']=='Field'
            assert native.request('struct A { int x; }; void f(){ A a; a.missing|; }',1,cpp=True)['diagnostics']
            code = '// 中文😀\r\nstruct A { int value; }; void f() { A a; a.val|ue = 1; }'
            target = native.request(code,3,cpp=True)['locations'][0]
            assert target['start'] == code.encode().index(b'value')
            assert 'value' in native.request(code,2,cpp=True)['hover']
            assert len(native.request(code,4,cpp=True)['locations']) >= 2
            ptr = native.request('struct A { int field; }; void f(){ A *a; a->| }',cpp=True)
            assert any(v['label']=='field' for v in ptr['items'])
            namespace = native.request('namespace ns { int count; void run(); } void f(){ ns::| }',cpp=True)
            assert any(v['label']=='run' for v in namespace['items'])
            header = str((ROOT/'artifacts'/'native-memory.hpp').resolve())
            code = '#include "native-memory.hpp"\nvoid f() { Model m; m.| }'
            result = native.request(code,cpp=True,additional=[(header, 'struct Model { int count; };')])
            assert any(v['label']=='count' for v in result['items'])
            result = native.request(code,cpp=True,additional=[(header, 'struct Model { int changed; };')])
            assert any(v['label']=='changed' for v in result['items']) and not any(v['label']=='count' for v in result['items'])
            header_error = native.request(code, 1, cpp=True, additional=[(header, '#include "missing-monaco-header-5817.hpp"\nstruct Model { int count; };')])
            assert any('missing-monaco-header-5817.hpp' in d['message'] for d in header_error['diagnostics'])
            if args.clang_resource_dir:
                flags = ['-resource-dir=' + str(Path(args.clang_resource_dir).resolve())]
                stl = native.request('#include <vector>\nvoid f() { std::vector<int> items; items.| }', cpp=True, arguments=flags)
                assert {'size', 'push_back'} <= {v['label'] for v in stl['items']}
                print("PASS: libclang STL template instance completion with explicit toolchain resource directory")
            # TU reparsing and concurrent requests use the native session mutex.
            with ThreadPoolExecutor(max_workers=4) as pool:
                values = list(pool.map(lambda _: native.request(source,cpp=True), range(16)))
            assert all(any(v['label']=='run' for v in r['items']) for r in values)
            print("PASS: Clang members/accessibility/chunks/diagnostics/definitions/references/arrow/namespace/unsaved-header reparse; 16 concurrent calls")
        else:
            print("SKIPPED: libclang semantic tests (pass --libclang or set MONACONATIVE_LIBCLANG)")
    finally:
        native.close()

if __name__ == '__main__':
    main()
